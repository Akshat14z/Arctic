const TABLES: Partial<Record<LangCode, Partial<Record<Key, string>>>> = { hi, ja };

/** A translator for one language: t("chat.empty", { name: "Kenji" }). Missing keys fall back to English. */
export function translator(lang: LangCode) {
  const table = TABLES[lang] ?? {};
  return (key: Key, vars?: Record<string, string | number>) => {
    const s = table[key] ?? en[key];
    return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
  };
}

export const I18N_TABLES = { en, hi, ja };
